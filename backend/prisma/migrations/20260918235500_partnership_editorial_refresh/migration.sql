FROM menu_end CROSS JOIN (VALUES
 ('d90918a0-0000-4000-8000-000000000001', 'Для бизнеса', '/business', 1),
 ('d90918a0-0000-4000-8000-000000000002', 'Рефералы и блогеры', '/partnerships', 2)
) AS additions(id, label, url, ordinal)
WHERE NOT EXISTS (SELECT 1 FROM "StorefrontMenuItem" WHERE "url" = additions.url)
ON CONFLICT ("id") DO NOTHING;

