-- Refresh only the original, unedited B2B editorial page. All copy stays in the page editor.
WITH refreshed AS (
  SELECT page."slug", jsonb_agg(
    CASE item.value->>'id'
      WHEN 'cover' THEN item.value || jsonb_build_object(
        'body', 'Персональные цены и актуальные остатки' || E'\n' || 'Календарь, команда и база клиентов' || E'\n' || 'Онлайн-запись под брендом вашего салона',
        'buttonLabel', 'Стать бизнес-клиентом')
      WHEN 'purchases' THEN item.value || jsonb_build_object(
        'title', 'Закупки без бесконечных прайсов',
        'body', 'Материалы SARKISIAN, персональные условия вашей компании, цены и остатки — в одном оптовом каталоге. Вы видите историю заказов и можете возвращаться к привычным позициям без переписок и таблиц.' || E'\n' || 'Условия закупок согласует менеджер после проверки компании. Розничные бонусы и реферальные награды на B2B-заказы не распространяются.')
      WHEN 'salon' THEN item.value || jsonb_build_object(
        'title', 'Расписание без хаоса',
        'body', 'Записи, услуги, команда и клиенты собраны в пространстве «Мой салон». В календаре на день и неделю видно загрузку мастеров: не нужно держать расписание в переписке или нескольких таблицах.' || E'\n' || 'Для каждого дня можно задать свои рабочие часы, выходные и перерывы. Клиенты увидят только доступное для записи время.')
      WHEN 'booking' THEN item.value || jsonb_build_object(
        'title', 'Клиенты записываются сами. Бренд — ваш.',
        'body', 'Настройте страницу салона с логотипом, адресом и контактами. Ссылку на запись можно разместить в соцсетях, а виджет — на собственном сайте.' || E'\n' || 'Клиент выберет услугу, мастера и свободное время. Вы управляете содержимым страницы и расписанием в кабинете.')
      WHEN 'supply' THEN item.value || jsonb_build_object(
        'title', 'Поставки на ваших условиях',
        'body', 'Состав заказа, способ оплаты и доставку обсудим с вашей компанией заранее. Отсрочка или рассрочка не подключается автоматически — такие условия согласуются отдельно.' || E'\n' || 'Обмен с 1С зависит от настроенной интеграции. Условия зарубежных поставок обсуждаются индивидуально.')
      WHEN 'start' THEN item.value || jsonb_build_object(
        'title', 'От заявки до первой закупки — три шага',
        'body', 'Оставьте заявку и расскажите о компании.' || E'\n' || 'Обсудите условия с менеджером и дождитесь активации.' || E'\n' || 'Откройте оптовый каталог или настройте салон и онлайн-запись.')
      WHEN 'contact' THEN item.value || jsonb_build_object(
        'title', 'Давайте начнём с ваших задач',
        'body', 'Расскажите, что важнее сейчас: поставки для команды, запись клиентов или оба направления. Поможем выбрать удобный формат и обсудим условия без лишних обещаний.')
      ELSE item.value
    END ORDER BY item.ordinality
  ) AS blocks
  FROM "StorefrontPage" page
  CROSS JOIN LATERAL jsonb_array_elements(page."blocks") WITH ORDINALITY AS item(value, ordinality)
  WHERE page."slug" = 'business'
    AND page."revision" = 3
    AND page."title" = E'Сильные материалы.\nУдобный бизнес.'
  GROUP BY page."slug"
)
UPDATE "StorefrontPage" page SET
  "title" = E'Закупки, запись, клиенты.\nВсё в одном месте.',
  "lead" = 'Персональные B2B-условия и заказ материалов — в одном пространстве. Расписание, команда, клиентская база и онлайн-запись — в другом. Один аккаунт для ежедневной работы салона.',
  "seoDescription" = 'SARKISIAN для бизнеса: персональные условия закупок, оптовый каталог, календарь салона, команда, клиенты и онлайн-запись в одном аккаунте.',
  "blocks" = refreshed.blocks,
  "revision" = page."revision" + 1,
  "updatedAt" = CURRENT_TIMESTAMP
FROM refreshed
WHERE page."slug" = refreshed."slug";
